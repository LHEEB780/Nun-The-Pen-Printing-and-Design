export function getCountryByName(nameOrCode: string): CountryInfo {
  const match = SUPPORTED_COUNTRIES.find(
    (c) =>
      c.nameAr === nameOrCode ||
      c.nameEn.toLowerCase() === nameOrCode.toLowerCase() ||
      c.code.toUpperCase() === nameOrCode.toUpperCase()
  );
  return match || SUPPORTED_COUNTRIES[0];
}
